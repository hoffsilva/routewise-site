        const HTML_LANG = {
            en: 'en',
            pt: 'pt-BR',
            fr: 'fr-CA',
            es: 'es',
        };

        function matchSupportedLanguage(rawLanguage) {
            if (!rawLanguage) return null;
            const normalized = rawLanguage.trim().replace(/_/g, '-').toLowerCase();
            if (normalized.startsWith('pt')) return 'pt';
            if (normalized.startsWith('fr')) return 'fr';
            if (normalized.startsWith('es')) return 'es';
            if (normalized.startsWith('en')) return 'en';
            return null;
        }

        function readStoredLanguage() {
            try {
                return window.localStorage.getItem(SITE_LANG_STORAGE_KEY);
            } catch {
                return null;
            }
        }

        function writeStoredLanguage(lang) {
            try {
                window.localStorage.setItem(SITE_LANG_STORAGE_KEY, lang);
            } catch {
                // Storage can be unavailable in private browsing; the URL still carries the language.
            }
        }

        function resolveLanguage() {
            const params = new URLSearchParams(window.location.search);
            const queryLanguage = params.get('lang');
            if (queryLanguage) return matchSupportedLanguage(queryLanguage) || 'en';

            const storedLanguage = matchSupportedLanguage(readStoredLanguage());
            if (storedLanguage) return storedLanguage;

            const browserLanguages = [
                ...((navigator.languages || [])),
                navigator.language,
            ];

            for (const browserLanguage of browserLanguages) {
                const matched = matchSupportedLanguage(browserLanguage);
                if (matched) return matched;
            }

            return 'en';
        }

        function translatePath(copy, key) {
            return key.split('.').reduce((value, part) => {
                if (!value) return null;
                return value[part];
            }, copy);
        }

        function isMobileDevice() {
            return /Android|iPhone|iPad|iPod|Mobile/i.test(navigator.userAgent || '');
        }

        function updateLocalizedLinks(lang) {
            document.querySelectorAll('[data-localized-link]').forEach((link) => {
                if (!link.dataset.originalHref) {
                    link.dataset.originalHref = link.getAttribute('href') || '';
                }

                const originalHref = link.dataset.originalHref;
                if (!originalHref) return;

                const url = new URL(originalHref, window.location.href);
                url.searchParams.set('lang', lang);
                link.setAttribute('href', `${url.pathname.split('/').pop()}${url.search}${url.hash}`);
            });
        }

        function updateScreenshots(lang, copy) {
            document.querySelectorAll('[data-screenshot]').forEach((image) => {
                const index = image.getAttribute('data-screenshot');
                image.setAttribute('src', `assets/screens/${lang}/image${index}.jpg`);
                image.setAttribute('alt', `${copy.screenshots.altPrefix} ${index}`);
            });
        }

        function applyLanguage(lang) {
            const copy = translations[lang] || translations.en;
            const description = document.getElementById('page-description');

            document.documentElement.lang = HTML_LANG[lang] || 'en';
            document.title = copy.meta.title;
            if (description) description.setAttribute('content', copy.meta.description);

            document.querySelectorAll('[data-i18n]').forEach((node) => {
                const key = node.getAttribute('data-i18n');
                const value = translatePath(copy, key);
                if (typeof value === 'string') node.textContent = value;
            });

            document.querySelectorAll('[data-i18n-html]').forEach((node) => {
                const key = node.getAttribute('data-i18n-html');
                const value = translatePath(copy, key);
                if (typeof value === 'string') node.innerHTML = value;
            });

            document.querySelectorAll('[data-lang-switch]').forEach((button) => {
                button.classList.toggle('is-active', button.getAttribute('data-lang-switch') === lang);
            });

            updateLocalizedLinks(lang);
            updateScreenshots(lang, copy);
        }

        function initLanguageSwitcher(activeLang) {
            document.querySelectorAll('[data-lang-switch]').forEach((button) => {
                button.addEventListener('click', () => {
                    const nextLang = matchSupportedLanguage(button.getAttribute('data-lang-switch')) || 'en';
                    const current = new URL(window.location.href);
                    current.searchParams.set('lang', nextLang);
                    writeStoredLanguage(nextLang);
                    window.history.replaceState({}, '', `${current.pathname}${current.search}${current.hash}`);
                    applyLanguage(nextLang);
                });
            });

            writeStoredLanguage(activeLang);
        }

        function setupStoreLinks() {
            document.querySelectorAll('#nav-store-link, #hero-store-link, #redirect-continue').forEach((link) => {
                link.href = APP_STORE_URL;
            });
        }

        function setupStoreRedirect(lang) {
            const current = new URL(window.location.href);
            const shouldStay = current.searchParams.get('stay') === '1';
            const forcedRedirect = current.searchParams.get('download') === '1' ||
                current.searchParams.get('store') === 'ios';

            if (shouldStay) return;

            if (forcedRedirect) {
                window.location.href = APP_STORE_URL;
                return;
            }

            if (!isMobileDevice()) return;

            const banner = document.getElementById('redirect-banner');
            const cancel = document.getElementById('redirect-cancel');
            const continueLink = document.getElementById('redirect-continue');

            if (!banner || !cancel || !continueLink) return;

            banner.classList.remove('is-hidden');
            continueLink.href = APP_STORE_URL;

            let cancelled = false;
            cancel.addEventListener('click', () => {
                cancelled = true;
                current.searchParams.set('stay', '1');
                current.searchParams.set('lang', lang);
                window.history.replaceState({}, '', `${current.pathname}${current.search}${current.hash}`);
                banner.classList.add('is-hidden');
            });

            window.setTimeout(() => {
                if (!cancelled) {
                    window.location.href = APP_STORE_URL;
                }
            }, 1400);
        }

        const activeLang = resolveLanguage();
        applyLanguage(activeLang);
        initLanguageSwitcher(activeLang);
        setupStoreLinks();
        setupStoreRedirect(activeLang);

        // Navbar scroll effect
        const nav = document.getElementById('nav');
        window.addEventListener('scroll', () => {
            if (window.scrollY > 50) {
                nav.classList.add('scrolled');
            } else {
                nav.classList.remove('scrolled');
            }
        });

        // Smooth scroll for anchor links
        document.querySelectorAll('a[href^="#"]').forEach(anchor => {
            anchor.addEventListener('click', function (e) {
                e.preventDefault();
                const href = this.getAttribute('href');
                if (href === '#') {
                    window.scrollTo({ top: 0, behavior: 'smooth' });
                    return;
                }
                const target = document.querySelector(href);
                if (target) {
                    target.scrollIntoView({
                        behavior: 'smooth',
                        block: 'start'
                    });
                }
            });
        });

        // Animate elements on scroll
        const observerOptions = {
            threshold: 0.1,
            rootMargin: '0px 0px -50px 0px'
        };

        const observer = new IntersectionObserver((entries) => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    entry.target.style.opacity = '1';
                    entry.target.style.transform = 'translateY(0)';
                }
            });
        }, observerOptions);

        document.querySelectorAll('.feature-card, .testimonial-card, .step, .comparison-card, .screenshot-card').forEach(el => {
            el.style.opacity = '0';
            el.style.transform = 'translateY(30px)';
            el.style.transition = 'opacity 0.6s ease, transform 0.6s ease';
            observer.observe(el);
        });
